insert into studio.adaptation_pages (person, adaptation_id, version_id) values (6786, 1, 1);
insert into studio.account_names (fname, person) values ('naaate', 6786);

-- Identity columns: continue after the seeded ids.
select setval(pg_get_serial_sequence('studio.adaptations', 'id'), 1);
select setval(pg_get_serial_sequence('studio.adaptation_versions', 'id'), 1);

commit;

-- Dry run: what would be kept, and who can read it.
select c.relname as table, c.relrowsecurity as rls,
       has_table_privilege('anon', c.oid, 'select') as anon_reads,
       has_table_privilege('anon', c.oid, 'insert') as anon_writes
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'studio' and c.relname in ('adaptations', 'adaptation_versions', 'adaptation_pages', 'account_names');
