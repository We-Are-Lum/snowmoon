-- 0012_adaptations.sql — adaptations, their versions, and each person's page per adaptation
-- (owner's URL scheme, 2026-10-17; design: docs/proposals/adaptation-urls.md).
-- NOT APPLIED. DRAFT until the owner says "publish". Change it freely until then.
--
-- MUST RUN AS postgres (the role that owns the `studio` schema), in the
-- Supabase SQL Editor. Requires 0001 (roles, studio schema) and 0011 (wallet accounts,
-- only for the meaning of a negative person number). Dry run first: paste everything, but
-- replace the final `commit;` with `rollback;`.
--
-- People are "person numbers", as in the image tables: a Farcaster FID (positive), or minus a
-- wallet account's id (0011), so a wallet account can never read as a FID.
--
-- What it adds:
-- 1. studio.adaptations: one row per adaptation (a root). The id is the number in the URL
--    (/@naaate/1, /1). The title can change; the owner is the person who started it.
-- 2. studio.adaptation_versions: every published version. parent_version_id is the version it
--    was forked from. A fork of a fork stays under the same root: (adaptation_id, parent) must
--    be a version of the same adaptation. The recipe is fixed once written; only `hidden` can
--    change. Hidden versions are not publicly readable.
-- 3. studio.adaptation_pages: what each person's page for an adaptation shows,
--    (person, adaptation) -> version. Written when they publish with "Show it on my page"
--    ticked (ticked by default on their first publish). The owner's word for this is
--    "featured"; it is named "pages" here because principle 5 (P5a) forbids that word as a
--    schema field. See the proposal, section "Principles".
-- 4. studio.account_names: the Farcaster names we have seen for a person, so a link with an
--    old name can still find them and redirect to the new one after a rename. Written only when
--    someone signs in or publishes, never when a page is viewed (owner, 2026-10-17).
-- 5. Seed: adaptation 1, "Fifteen Days", owned by FID 6786 (the owner, @naaate; SYSTEM_FID
--    in src/lib/config.ts), its first version, and the owner's page pointing at it.
--    The video URL in the seed is a PLACEHOLDER (null) until the cut is published.

begin;

-- ---------------------------------------------------------------------------
-- 1. Adaptations (roots).
-- ---------------------------------------------------------------------------

create table studio.adaptations (
  id bigint generated by default as identity primary key,
  owner_person bigint not null check (owner_person <> 0),
  title text not null check (length(btrim(title)) between 1 and 120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 2. Versions. Append-only except `hidden`.
-- ---------------------------------------------------------------------------

create table studio.adaptation_versions (
  id bigint generated by default as identity primary key,
  adaptation_id bigint not null references studio.adaptations(id),
  parent_version_id bigint,
  author_person bigint not null check (author_person <> 0),
  -- What the version is: at least { video_url }, plus where its full recipe lives (recipe_url),
  -- poster_url, its AI declaration (ai_label), after_chapter and spoilers_through.
  -- Shape: VersionRecipe in src/lib/adaptation-pages.ts.
  recipe jsonb not null check (jsonb_typeof(recipe) = 'object'),
  created_at timestamptz not null default now(),
  hidden boolean not null default false,
  unique (adaptation_id, id),
  -- A fork's parent is a version of the same root, so forks of forks stay under it.
  foreign key (adaptation_id, parent_version_id) references studio.adaptation_versions (adaptation_id, id),
  check (parent_version_id is null or parent_version_id <> id)
);
create index adaptation_versions_author on studio.adaptation_versions (adaptation_id, author_person, created_at desc);
create index adaptation_versions_parent on studio.adaptation_versions (parent_version_id);

create function studio.adaptation_version_fixed() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'adaptation_versions is append-only: DELETE rejected';
  end if;
  if new.id <> old.id or new.adaptation_id <> old.adaptation_id
     or new.parent_version_id is distinct from old.parent_version_id
     or new.author_person <> old.author_person or new.recipe <> old.recipe
     or new.created_at <> old.created_at then
    raise exception 'adaptation_versions: only hidden can change';
  end if;
  return new;
end;
$$;
create trigger adaptation_versions_fixed
  before update or delete on studio.adaptation_versions
  for each row execute function studio.adaptation_version_fixed();
create trigger adaptation_versions_no_truncate
  before truncate on studio.adaptation_versions
  for each statement execute function studio.reject_mutation();

-- ---------------------------------------------------------------------------
-- 3. Each person's page per adaptation.
-- ---------------------------------------------------------------------------

create table studio.adaptation_pages (
  person bigint not null check (person <> 0),
  adaptation_id bigint not null references studio.adaptations(id),
  version_id bigint not null,
  updated_at timestamptz not null default now(),
  primary key (person, adaptation_id),
  -- The version is under the same root.
  foreign key (adaptation_id, version_id) references studio.adaptation_versions (adaptation_id, id)
);
create index adaptation_pages_version on studio.adaptation_pages (version_id);

-- ---------------------------------------------------------------------------
-- 4. Names seen, for redirects after a rename.
-- ---------------------------------------------------------------------------

create table studio.account_names (
  fname text primary key check (fname ~ '^[a-z0-9][a-z0-9.-]{0,30}$'),
  person bigint not null check (person > 0),
  seen_at timestamptz not null default now()
);
create index account_names_person on studio.account_names (person, seen_at desc);

-- ---------------------------------------------------------------------------
-- RLS. Public read of what is published; the server (studio_writer) writes after checking
-- the signed-in person. Nothing here is private except hidden versions.
-- ---------------------------------------------------------------------------

alter table studio.adaptations         enable row level security;
alter table studio.adaptation_versions enable row level security;
alter table studio.adaptation_pages    enable row level security;
alter table studio.account_names       enable row level security;

create policy public_read on studio.adaptations for select using (true);
create policy public_read on studio.adaptation_versions for select using (not hidden);
create policy public_read on studio.adaptation_pages for select using (
  exists (select 1 from studio.adaptation_versions v where v.id = version_id and not v.hidden)
);
-- No public read: past names are private, used only by the server to redirect (owner, 2026-10-17).

create policy writer_read on studio.adaptations for select to studio_writer using (true);
create policy writer_insert on studio.adaptations for insert to studio_writer with check (true);
create policy writer_update on studio.adaptations for update to studio_writer using (true) with check (true);
create policy writer_read on studio.adaptation_versions for select to studio_writer using (true);
create policy writer_insert on studio.adaptation_versions for insert to studio_writer with check (true);
create policy writer_update on studio.adaptation_versions for update to studio_writer using (true) with check (true);
create policy writer_read on studio.adaptation_pages for select to studio_writer using (true);
create policy writer_insert on studio.adaptation_pages for insert to studio_writer with check (true);
create policy writer_update on studio.adaptation_pages for update to studio_writer using (true) with check (true);
create policy writer_read on studio.account_names for select to studio_writer using (true);
create policy writer_insert on studio.account_names for insert to studio_writer with check (true);
create policy writer_update on studio.account_names for update to studio_writer using (true) with check (true);

-- anon and authenticated read only (0001's default privileges gave them select; take back the rest).
revoke insert, update, delete, truncate, references, trigger on
  studio.adaptations, studio.adaptation_versions, studio.adaptation_pages, studio.account_names
  from anon, authenticated;
-- Past names are private (owner, 2026-10-17): no public read at all, only the server's writer role.
revoke select on studio.account_names from anon, authenticated;
-- The writer never deletes; a version is hidden, never removed.
revoke delete, truncate, references, trigger on
  studio.adaptations, studio.adaptation_versions, studio.adaptation_pages, studio.account_names
  from studio_writer;
grant select, insert, update on
  studio.adaptations, studio.adaptation_versions, studio.adaptation_pages, studio.account_names
  to studio_writer;

revoke execute on function studio.adaptation_version_fixed() from public;

-- ---------------------------------------------------------------------------
-- 5. Seed: adaptation 1 = Fifteen Days, owned by FID 6786 (@naaate).
-- ---------------------------------------------------------------------------

insert into studio.adaptations (id, owner_person, title) values (1, 6786, 'Fifteen Days');
-- The cut is on version 1 itself (owner, 2026-10-17: nothing is public yet, so /@naaate/1/v/1 is the
-- exact cut the posts link to): v5 of the coverage cut, sha256 f76a3312…, and the café master as
-- its poster, both named by their sha256 on media.snowmoon.party and uploaded in publish step (b)
-- (npm run publish:scene-video). Versions are append-only from here on.
insert into studio.adaptation_versions (id, adaptation_id, parent_version_id, author_person, recipe)
values (1, 1, null, 6786, jsonb_build_object(
  'video_url', 'https://media.snowmoon.party/scenes/fifteen-days/v1/fifteen-days-f76a3312e1fd.mp4',
  'poster_url', 'https://media.snowmoon.party/scenes/fifteen-days/v1/fifteen-days-poster-3caad9b75656.jpg',
  'recipe_url', 'https://github.com/We-Are-Lum/snowmoon/tree/main/adaptations/fifteen-days',
  'ai_label', 'Pictures: AI-generated, not by the author · Voices: @naaate''s performances, AI-converted.',  -- owner's wording, approved 2026-10-17
  'after_chapter', 14,
  'spoilers_through', 19
