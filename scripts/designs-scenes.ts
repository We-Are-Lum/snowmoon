/**
 * Which place each scene of the book is in, for the place sheets (owner, 2026-10-10: images should
 * know "what location is in the background"). Derived, with no model, from the book's text
 * (content/snowmoon/text), the location files' facts (content/snowmoon/designs/locations) and the
 * seeded images' locations (content/snowmoon/illustrations/published.json), by the rule in
 * src/lib/images/sheets.ts (SCENE_RULE). Written to content/snowmoon/designs/scenes.json so every
 * assignment, and the block that gives it, can be reviewed.
 *
 *   npm run designs:scenes            write the file
 *   npm run designs:scenes -- --check exit 1 if the file is out of date
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { bookChapters, deriveScenes, SCENE_RULE, SCENES_FILE, seededImages, sheetPlaces, type ScenesFile } from '../src/lib/images/sheets';

const ROOT = path.resolve(import.meta.dirname, '..');
const file = path.join(ROOT, SCENES_FILE);
export function buildScenes(): ScenesFile {
  return {
    about: 'Generated by npm run designs:scenes (scripts/designs-scenes.ts); do not edit by hand. Each part of a scene, its place sheet (a slug of content/snowmoon/designs/locations, or null), and the block that is the evidence. No model was used.',
    rule: SCENE_RULE,
    parts: deriveScenes(bookChapters(), sheetPlaces(), seededImages()),
  };
}
const text = (s: ScenesFile) => JSON.stringify(s, null, 1) + '\n';

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = text(buildScenes());
  const parts = JSON.parse(next).parts as ScenesFile['parts'];
  const scenes = new Map<string, boolean>();
  for (const p of parts) scenes.set(`${p.chapter}-${p.scene}`, (scenes.get(`${p.chapter}-${p.scene}`) ?? false) || p.place !== null);
  const withPlace = [...scenes.values()].filter(Boolean).length;
  console.log(`${scenes.size} scenes in ${parts.length} parts; ${withPlace} scenes with a place, ${scenes.size - withPlace} without; ${parts.filter((p) => p.place).length} parts with a place, ${parts.filter((p) => !p.place).length} without; ${new Set(parts.map((p) => p.place).filter(Boolean)).size} of ${sheetPlaces().length} places used`);
  if (process.argv.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== next) {
      console.error(`${SCENES_FILE} is out of date: run npm run designs:scenes`);
      process.exit(1);
    }
    console.log(`${SCENES_FILE} is up to date`);
  } else {
    writeFileSync(file, next);
    console.log(`written: ${SCENES_FILE}`);
  }
}
