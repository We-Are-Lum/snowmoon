const COLORS: Record<string, [number, number, number]> = {
  sea: [70, 110, 160], 'sea ice': [205, 220, 232], ice: [242, 245, 248], tundra: [190, 192, 170], 'boreal forest': [72, 104, 78], temperate: [118, 156, 92], steppe: [190, 180, 120], desert: [222, 200, 150], subtropical: [150, 170, 90], tropical: [70, 140, 70],
};
function shade(g: Generated, zoneOf: (k: number) => string | null, scale: number): { w: number; h: number; rgb: Uint8Array } {
  const G = g.grid, w = G.w * scale, h = G.h * scale, rgb = new Uint8Array(w * h * 3);
  const flipY = G.dy > 0 && G.name !== 'northshore'; // north up
  const zmax = Math.max(1, ...Array.from(G.z));
  const river = new Uint8Array(G.w * G.h);
  for (const rr of g.rivers) for (const [x, y] of rr.points) river[Math.round((y - G.y0) / G.dy) * G.w + Math.round((x - G.x0) / G.dx)] = 1;
  for (let j = 0; j < G.h; j++) for (let i = 0; i < G.w; i++) {
    const k = j * G.w + i, z = G.z[k];
    let c: [number, number, number];
    if (z < 0) { const d = Math.min(1, -z / 2000); c = [70 - 30 * d, 115 - 45 * d, 165 - 40 * d]; const zn = zoneOf(k); if (zn === 'sea ice') c = COLORS['sea ice']; }
    else if (g.lakes[k]) c = [95, 140, 185];
    else if (river[k]) c = [85, 130, 185];
    else {
      const zn = zoneOf(k);
      const baseC = zn ? COLORS[zn] : [128, 160, 100];
      const t = Math.min(1, z / zmax);
      c = [baseC[0] + (225 - baseC[0]) * t * 0.6, baseC[1] + (215 - baseC[1]) * t * 0.6, baseC[2] + (200 - baseC[2]) * t * 0.6];
      // hillshade: Lambert light from the north-west, 45 degrees up (heights exaggerated 3x at world scale)
      const ex = G.name === 'world' ? 3 : 1;
      const zw = G.z[j * G.w + Math.max(0, i - 1)], ze = G.z[j * G.w + Math.min(G.w - 1, i + 1)];
      const jn = Math.min(G.h - 1, Math.max(0, j + (G.dy > 0 ? 1 : -1))), js = Math.min(G.h - 1, Math.max(0, j - (G.dy > 0 ? 1 : -1)));
      const zN = G.z[jn * G.w + i], zS = G.z[js * G.w + i];
      const gx = (ex * (Math.max(0, ze) - Math.max(0, zw))) / (2 * G.kmx(cx(G, i), cy(G, j)) * Math.abs(G.dx) * 1000);
      const gy = (ex * (Math.max(0, zN) - Math.max(0, zS))) / (2 * G.kmy * Math.abs(G.dy) * 1000);
      const nlen = Math.hypot(gx, gy, 1);
      const lam = (gx * 0.5 - gy * 0.5 + 0.7071) / nlen; // light vector (-0.5, 0.5, 0.7071): from the north-west
      const light = 0.45 + 0.75 * Math.max(0, lam) / 0.7071 * 0.75;
      c = [c[0] * light, c[1] * light, c[2] * light];
    }
    for (let b = 0; b < scale; b++) for (let a = 0; a < scale; a++) {
      const px = i * scale + a, py = (flipY ? G.h - 1 - j : j) * scale + b;
      const o = (py * w + px) * 3;
      rgb[o] = Math.max(0, Math.min(255, c[0])); rgb[o + 1] = Math.max(0, Math.min(255, c[1])); rgb[o + 2] = Math.max(0, Math.min(255, c[2]));
    }
  }
  return { w, h, rgb };
}

