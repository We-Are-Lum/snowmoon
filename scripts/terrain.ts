function testSeed(r: Run) {
  const gm = generatedMaps(r);
  const mapResults: { map: string; line: string; test: string; ok: boolean; got: string; expect?: string }[] = [];
  for (const m of [gm.world, gm.meldan, gm.pafogai]) {
    for (const t of m.tests as Test[]) {
      let res: { ok: boolean; got: string };
      try { res = run(m, t); } catch (e) { res = { ok: false, got: `error: ${(e as Error).message}` }; }
      const pass = t.expect === 'conflict' ? !res.ok : res.ok;
      mapResults.push({ map: m.map, line: t.line, test: t.test, ok: pass, got: res.got, expect: t.expect });
    }
  }
  const terrain = terrainTests(r);
  const failed = [...gm.missing.map((id) => `outline missing: ${id}`), ...mapResults.filter((x) => !x.ok).map((x) => `${x.map} ${x.line} ${x.test}: ${x.got}`), ...terrain.filter((x) => !x.ok).map((x) => `terrain: ${x.id}: ${x.got}`)];
  return { gm, mapResults, terrain, failed };
}

