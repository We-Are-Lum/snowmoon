/** Pins are applied with a bounding box test first; polygon pins are expensive on big grids. */
function applyPins(g: GridSpec, z: Float32Array, pins: Pin[]) {
  // the held core reaches out irregularly into the inner half of the band; the outer half is left to the terrain
  const coastNz = new Noise2(9091);
  const wander = (i: number, j: number, off: number) => 1 - 0.5 * Math.min(1, Math.max(0, 0.5 + 0.9 * coastNz.fbm(i / 3 + off, j / 3, 4)));
  for (const p of pins) {
    let box: [number, number, number, number] | null = null;
    const pad = (km: number) => km / g.dx + 2;
    if ('poly' in p && p.kind !== 'cover') { const xs = p.poly.map((q) => q[0]), ys = p.poly.map((q) => q[1]); box = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]; }
    if (p.kind === 'land-disk') box = [p.c[0] - pad(p.r) * g.dx * 2, p.c[1] - pad(p.r) * g.dx, p.c[0] + pad(p.r) * g.dx * 2, p.c[1] + pad(p.r) * g.dx];
    if (p.kind === 'sea-ring') box = [p.c[0] - pad(p.r2) * g.dx * 2, p.c[1] - pad(p.r2) * g.dx, p.c[0] + pad(p.r2) * g.dx * 2, p.c[1] + pad(p.r2) * g.dx];
    if (p.kind === 'shape' && p.bbox) box = p.bbox;
    if (p.kind === 'river' || p.kind === 'cover') continue;
    const i0 = box ? Math.max(0, Math.floor((box[0] - g.x0) / g.dx) - 1) : 0, i1 = box ? Math.min(g.w - 1, Math.ceil((box[2] - g.x0) / g.dx) + 1) : g.w - 1;
    const j0 = box ? Math.max(0, Math.floor((box[1] - g.y0) / g.dy) - 1) : 0, j1 = box ? Math.min(g.h - 1, Math.ceil((box[3] - g.y0) / g.dy) + 1) : g.h - 1;
    for (let j = j0; j <= j1; j++)
      for (let i = i0; i <= i1; i++) {
        const k = idx(g, i, j), q: XY = [g.x0 + i * g.dx, g.y0 + j * g.dy];
        if (p.kind === 'sea') { const sd = polySigned(g, q, p.poly, p.open), band = p.bandNear && kmDist(g, q, p.bandNear.c) < p.bandNear.r ? p.bandNear.band : p.band; if (sd > band * wander(i, j, 50)) z[k] = Math.min(z[k], -12 - 25 * smooth((sd - band) / 45)); }
        else if (p.kind === 'land') { if (polySigned(g, q, p.poly) > p.band * wander(i, j, 0)) z[k] = Math.max(z[k], p.min); }
        else if (p.kind === 'land-box') { if (pointInPoly(q[0], q[1], p.poly) && p.seas.every((s) => polySigned(g, q, s) < -p.band)) z[k] = Math.max(z[k], p.min); }
        else if (p.kind === 'sea-poly') { const sd = polySigned(g, q, p.poly); if (sd > 0) z[k] = Math.min(z[k], -15 + (p.depth + 15) * smooth(sd / 30)); }
        else if (p.kind === 'land-disk') { if (kmDist(g, q, p.c) <= p.r) z[k] = Math.max(z[k], p.min); }
        else if (p.kind === 'sea-ring') { const d = kmDist(g, q, p.c); if (d >= p.r1 && d <= p.r2) z[k] = Math.min(z[k], p.depth); }
        else if (p.kind === 'shape') { const s = p.f(q[0], q[1]); if (s) z[k] = z[k] * (1 - s.weight) + s.target * s.weight; }
      }
  }
}
/** Soft pulls around coast pins, so the book's coasts are approached smoothly rather than stamped. */
function softPins(g: GridSpec, z: Float32Array, pins: Pin[]) {
  const coastNz = new Noise2(9091);
  for (const p of pins) {
    if ((p.kind !== 'sea' && p.kind !== 'land') || p.band <= 0) continue; // coasts only: pins with a band the coast may move within
    const xs = p.poly.map((q) => q[0]), ys = p.poly.map((q) => q[1]);
    const m = (Math.max(p.band, p.kind === 'sea' && p.bandNear ? p.bandNear.band : 0) + 30) / g.dx;
    const i0 = Math.max(0, Math.floor((Math.min(...xs) - g.x0) / g.dx - m * 2)), i1 = Math.min(g.w - 1, Math.ceil((Math.max(...xs) - g.x0) / g.dx + m * 2));
    const j0 = Math.max(0, Math.floor((Math.min(...ys) - g.y0) / g.dy - m)), j1 = Math.min(g.h - 1, Math.ceil((Math.max(...ys) - g.y0) / g.dy + m));
    for (let j = j0; j <= j1; j++)
      for (let i = i0; i <= i1; i++) {
        // the coast settles irregularly inside its band, not along the drawn polygon
        const q: XY = [g.x0 + i * g.dx, g.y0 + j * g.dy], band = p.kind === 'sea' && p.bandNear && kmDist(g, q, p.bandNear.c) < p.bandNear.r ? p.bandNear.band : p.band;
        const s = polySigned(g, [g.x0 + i * g.dx, g.y0 + j * g.dy], p.poly, p.kind === 'sea' ? p.open : undefined) + band * (1.5 * coastNz.fbm(i / 6, j / 6, 3) + 0.7 * coastNz.ridged(i / 2.5 + 9, j / 2.5, 2) - 0.35);
        if (s > -band - 10 && s <= band) {
          const t = smooth((s + band + 10) / (2 * band + 10));
          z[idx(g, i, j)] += (p.kind === 'sea' ? -300 : 300) * t;
        }
      }
  }
}

/** A drawn course made to wander: resampled every cell and pushed sideways by smooth noise, ends held. */
function meander(g: GridSpec, path: XY[], ampKm: number): XY[] {
  const nz = new Noise2(4242);
  const out: XY[] = [];
  let total = 0;
  for (let s = 0; s < path.length - 1; s++) total += kmDist(g, path[s], path[s + 1]);
  let along = 0;
  for (let s = 0; s < path.length - 1; s++) {
    const a = path[s], b = path[s + 1], len = kmDist(g, a, b), n = Math.max(2, Math.ceil(len / g.dx));
    const nx = -(b[1] - a[1]), ny = b[0] - a[0], nl = Math.hypot(nx, ny) || 1;
    for (let t = 0; t < n; t++) {
      const f = t / n, d = along + len * f, taper = Math.min(1, d / (ampKm * 3), (total - d) / (ampKm * 3));
      const off = ampKm * taper * nz.fbm(d / (ampKm * 2.5), 0.5, 3) * 1.6;
      out.push([a[0] + (b[0] - a[0]) * f + (nx / nl) * off * (g.dx / kmDist(g, [0, 0], [g.dx, 0])), a[1] + (b[1] - a[1]) * f + (ny / nl) * off * (g.dy / kmDist(g, [0, 0], [0, g.dy]))]);
    }
    along += len;
  }
  out.push(path[path.length - 1]);
  return out;
}
function carve(g: GridSpec, z: Float32Array, pins: Pin[]): Uint8Array {
  const carved = new Uint8Array(g.w * g.h);
  for (const p of pins) {
    if (p.kind !== 'river') continue;
    const path = p.meanderKm ? meander(g, p.path, p.meanderKm) : p.path;
    let level = Infinity;
    for (let s = 0; s < path.length - 1; s++) {
      const a = path[s], b = path[s + 1];
      const steps = Math.max(2, Math.ceil(kmDist(g, a, b) / (0.4 * g.dx)));
      for (let t = 0; t <= steps; t++) {
        const x = a[0] + ((b[0] - a[0]) * t) / steps, y = a[1] + ((b[1] - a[1]) * t) / steps;
        const here = bilinear(g, z, x, y);
        level = level === Infinity ? here : Math.min(level - 0.02, here);
        if (s === path.length - 2) level = Math.min(level, t === steps ? -8 : -1);
        const ci = Math.round((x - g.x0) / g.dx), cj = Math.round((y - g.y0) / g.dy);
        const r = Math.ceil(p.width / g.dx) + 1;
        for (let jj = cj - r; jj <= cj + r; jj++)
          for (let ii = ci - 2 * r; ii <= ci + 2 * r; ii++) {
            if (ii < 0 || jj < 0 || ii >= g.w || jj >= g.h) continue;
            const d = kmDist(g, [g.x0 + ii * g.dx, g.y0 + jj * g.dy], [x, y]);
            if (d <= p.width) { z[idx(g, ii, jj)] = Math.min(z[idx(g, ii, jj)], level); carved[idx(g, ii, jj)] = 1; }
            else if (d <= p.width * 3) { const k = idx(g, ii, jj); z[k] = Math.min(z[k], level + (z[k] - level) * smooth((d - p.width) / (2 * p.width))); }
          }
      }
    }
  }
  return carved;
}

// ---- droplet hydraulic erosion (after Hans Theobald Beyer, 2015)
function erodeDroplets(g: GridSpec, z: Float32Array, n: number, seed: number, heightScaleM: number, o = { inertia: 0.05, capacity: 6, minSlope: 0.005, deposit: 0.3, erode: 0.35, evaporate: 0.02, gravity: 4, maxSteps: 60, radius: 3 }) {
  const rnd = mulberry32(seed);
  const brush: [number, number, number][] = [];
  let wsum = 0;
  for (let dj = -o.radius; dj <= o.radius; dj++) for (let di = -o.radius; di <= o.radius; di++) { const d = Math.hypot(di, dj); if (d < o.radius) { brush.push([di, dj, o.radius - d]); wsum += o.radius - d; } }
  for (const b of brush) b[2] /= wsum;
  const H = (k: number) => z[k] / heightScaleM;
  const w = g.w, h = g.h;
  const sample = (x: number, y: number) => {
    const i = Math.floor(x), j = Math.floor(y), u = x - i, v = y - j, k = j * w + i;
    const a = H(k), b = H(k + 1), c = H(k + w), d = H(k + w + 1);
    return { height: a * (1 - u) * (1 - v) + b * u * (1 - v) + c * (1 - u) * v + d * u * v, gx: (b - a) * (1 - v) + (d - c) * v, gy: (c - a) * (1 - u) + (d - b) * u };
  };
  for (let d = 0; d < n; d++) {
    let x = 1 + rnd() * (w - 3), y = 1 + rnd() * (h - 3);
    if (z[Math.floor(y) * w + Math.floor(x)] <= 0) continue;
    let dx = 0, dy = 0, speed = 1, water = 1, sediment = 0;
    for (let step = 0; step < o.maxSteps; step++) {
      const i = Math.floor(x), j = Math.floor(y), u = x - i, v = y - j, k = j * w + i;
      const s0 = sample(x, y);
      dx = dx * o.inertia - s0.gx * (1 - o.inertia);
      dy = dy * o.inertia - s0.gy * (1 - o.inertia);
      const len = Math.hypot(dx, dy);
      if (len < 1e-9) break;
      dx /= len; dy /= len;
      const nx = x + dx, ny = y + dy;
      if (nx < 1 || ny < 1 || nx >= w - 2 || ny >= h - 2) break;
      const dh = sample(nx, ny).height - s0.height;
      const cap = Math.max(-dh * speed * water * o.capacity, o.minSlope);
      if (sediment > cap || dh > 0) {
        const amt = dh > 0 ? Math.min(dh, sediment) : (sediment - cap) * o.deposit;
        sediment -= amt;
        const a = amt * heightScaleM;
        z[k] += a * (1 - u) * (1 - v); z[k + 1] += a * u * (1 - v); z[k + w] += a * (1 - u) * v; z[k + w + 1] += a * u * v;
      } else {
        const amt = Math.min((cap - sediment) * o.erode, -dh);
        for (const [di, dj, bw] of brush) {
          const ii = i + di, jj = j + dj;
          if (ii < 0 || jj < 0 || ii >= w || jj >= h) continue;
          const kk = jj * w + ii;
          const take = Math.min(amt * bw, Math.max(0, H(kk) - 0)) * heightScaleM;
          z[kk] -= take;
          sediment += take / heightScaleM;
        }
      }
      speed = Math.sqrt(Math.max(0, speed * speed + dh * o.gravity));
      water *= 1 - o.evaporate;
      x = nx; y = ny;
      if (z[Math.floor(y) * w + Math.floor(x)] < 0) break; // reached the sea: what it carries settles offshore
    }
  }
}

// ---- lakes only where they make sense, then drainage and rivers
/** A river from its head to the sea, the frame's edge, a lake or the river it joins; flows are the drainage area at each point. */
type River = { points: XY[]; flow_km2: number; flows: number[] };
type Hydro = { lakes: Uint8Array; filled: Float32Array; acc: Float32Array; rec: Int32Array; rivers: River[] };
function hydrology(g: GridSpec, z: Float32Array, lakeMinCells: number, lakeMinDepthM: number, riverKm2: number, noRiver?: (x: number, y: number) => boolean, noLake?: (x: number, y: number) => boolean, forced?: Uint8Array, maxLakes = 10, lakeMaxCells = Infinity, minBranchCells = 0): Hydro {
  const parent = new Int32Array(g.w * g.h);
  const F = fillMeander(g, z, 811, parent);
  const lakes = new Uint8Array(g.w * g.h);
  const seen = new Uint8Array(g.w * g.h);
  const basins: { cells: number[]; ok: boolean; breach: boolean }[] = [];
  for (let k = 0; k < z.length; k++) {
    if (seen[k] || z[k] < 0 || F[k] - z[k] <= 0.5) continue;
    // one depression: its cells, area and depth
    const cells: number[] = [];
    const stack = [k];
    seen[k] = 1;
    let depth = 0;
    while (stack.length) {
      const c = stack.pop()!;
      cells.push(c);
      depth = Math.max(depth, F[c] - z[c]);
      const i = c % g.w, j = Math.floor(c / g.w);
      for (const [di, dj] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const ni = i + di, nj = j + dj;
        if (ni < 0 || nj < 0 || ni >= g.w || nj >= g.h) continue;
        const nk = nj * g.w + ni;
        if (!seen[nk] && z[nk] >= 0 && F[nk] - z[nk] > 0.5) { seen[nk] = 1; stack.push(nk); }
      }
    }
    const inNoLake = !!noLake && cells.some((c2) => noLake(...cxy(g, c2)));
    const tooBig = cells.length > lakeMaxCells;
    const ok = cells.length >= lakeMinCells && depth >= lakeMinDepthM && !inNoLake && !tooBig;
    basins.push({ cells, ok, breach: (inNoLake || tooBig) && depth > 8 });
  }
  // only the largest qualifying basins hold lakes; every other hollow fills with sediment
  const kept = new Set(basins.filter((b) => b.ok).sort((a, b) => b.cells.length - a.cells.length).slice(0, maxLakes));
  for (const b of basins) {
    if (kept.has(b)) { for (const c of b.cells) lakes[c] = 1; continue; }
    if (b.breach) {
      // where the book has no lake, a basin drains: cut a channel from its lowest point out through its rim
      let low = b.cells[0];
      for (const c of b.cells) if (z[c] < z[low]) low = c;
      let c = low, level = z[low];
      for (let guard = 0; guard < g.w * g.h && c >= 0; guard++) {
        const p = parent[c];
        if (p < 0) break;
        level = Math.max(0.5, level - 0.05); // a channel on land never cuts below sea level
        if (z[p] <= level) break;
        z[p] = level;
        c = p;
      }
      continue;
    }
    for (const c of b.cells) z[c] = F[c]; // a small hollow fills with sediment
  }
  const filled = fillMeander(g, z, 977);
  const rec = receivers(g, filled);
  const acc = accumulation(g, filled, rec);
  // rivers: trace from heads, stop at the sea, the frame edge, a lake, or ground where none is drawn
  const isRiver = (k: number) => filled[k] >= 0 && !lakes[k] && ((forced && forced[k] === 1) || (acc[k] >= riverKm2 && !(noRiver && noRiver(...cxy(g, k)))));
  const hasUp = new Uint8Array(z.length);
  for (let k = 0; k < z.length; k++) if (isRiver(k) && rec[k] >= 0) hasUp[rec[k]] = 1;
  const used = new Uint8Array(z.length);
  const rivers: River[] = [];
  // heads in order of their path to the mouth, longest first: the longest stream claims the main
  // channel, so every later head traces only its own branch, and short branches are pruned
  const heads: { k: number; len: number }[] = [];
  for (let k = 0; k < z.length; k++) {
    if (!isRiver(k) || hasUp[k]) continue;
    let len = 0;
    for (let c = k; c >= 0 && isRiver(c) && len < 100000; c = rec[c]) len++;
    heads.push({ k, len });
  }
  heads.sort((a, b) => b.len - a.len);
  for (const { k } of heads) {
    const ptsR: XY[] = [], flows: number[] = [], cells: number[] = [];
    let c = k, joined = false;
    for (;;) {
      ptsR.push(cxy(g, c));
      flows.push(Math.round(acc[c]));
      if (used[c] && ptsR.length > 1) { joined = true; break; }
      cells.push(c);
      const r = rec[c];
      if (r < 0) break;
      if (!isRiver(r)) { ptsR.push(cxy(g, r)); flows.push(Math.round(acc[c])); break; }
      c = r;
    }
    const isForced = !!forced && cells.some((q) => forced[q] === 1);
    if (ptsR.length <= 2 || (joined && cells.length < minBranchCells && !isForced)) continue;
    for (const q of cells) used[q] = 1;
    rivers.push({ points: ptsR, flow_km2: flows[flows.length - 1], flows });
  }
  return { lakes, filled, acc, rec, rivers };
}

/** Priority-flood, with an epsilon that varies smoothly in space: water crossing a flat follows the
 * varying gradient and meanders, rather than running in straight lines. */
function fillMeander(g: GridSpec, z: Float32Array, seed: number, parentOut?: Int32Array): Float32Array {
  const F = new Float32Array(z);
  if (parentOut) parentOut.fill(-1);
  const done = new Uint8Array(z.length);
  const nz = new Noise2(seed);
  const eps = (k: number) => { const [x, y] = cxy(g, k); const v = 0.5 + 0.5 * nz.fbm(x / (g.dx * 14), y / (g.dy * 14), 4); return 0.002 + 0.06 * v * v; };
  const hz: number[] = [], hk: number[] = [];
  const push = (v: number, k: number) => { hz.push(v); hk.push(k); let c = hz.length - 1; while (c > 0) { const p = (c - 1) >> 1; if (hz[p] <= hz[c]) break; [hz[p], hz[c]] = [hz[c], hz[p]]; [hk[p], hk[c]] = [hk[c], hk[p]]; c = p; } };
  const pop = (): number => { const top = hk[0]; const lz = hz.pop()!, lk = hk.pop()!; if (hz.length) { hz[0] = lz; hk[0] = lk; let c = 0; for (;;) { const l = 2 * c + 1, r = l + 1; let m = c; if (l < hz.length && hz[l] < hz[m]) m = l; if (r < hz.length && hz[r] < hz[m]) m = r; if (m === c) break; [hz[m], hz[c]] = [hz[c], hz[m]]; [hk[m], hk[c]] = [hk[c], hk[m]]; c = m; } } return top; };
  for (let j = 0; j < g.h; j++) for (let i = 0; i < g.w; i++) { const k = j * g.w + i; if (z[k] < 0 || i === 0 || j === 0 || i === g.w - 1 || j === g.h - 1) { done[k] = 1; push(F[k], k); } }
  while (hz.length) {
    const k = pop();
    const i = k % g.w, j = Math.floor(k / g.w);
    for (let dj = -1; dj <= 1; dj++) for (let di = -1; di <= 1; di++) {
      if (!di && !dj) continue;
      const ni = i + di, nj = j + dj;
      if (ni < 0 || nj < 0 || ni >= g.w || nj >= g.h) continue;
      const n = nj * g.w + ni;
      if (done[n]) continue;
      done[n] = 1;
      F[n] = Math.max(F[n], F[k] + eps(n));
      if (parentOut) parentOut[n] = k;
      push(F[n], n);
    }
  }
  return F;
}

// ---- climate and biomes
const BIOMES = ['sea', 'lake', 'ice', 'tundra', 'alpine', 'boreal pine forest', 'temperate forest', 'temperate grassland', 'steppe', 'desert', 'subtropical forest', 'dry savanna', 'tropical forest', 'built-up'] as const;
type Biome = (typeof BIOMES)[number];
const B = (b: Biome) => BIOMES.indexOf(b);
const FOREST = new Set([B('boreal pine forest'), B('temperate forest'), B('subtropical forest'), B('tropical forest')]);
/** Mean annual temperature: colder toward the pole and with height. */
const tempC = (lat: number, h: number) => -25 + 52 * Math.cos(rad(lat)) - 0.0065 * Math.max(0, h);
function climate(g: GridSpec, z: Float32Array, lakes: Uint8Array, latOf: (y: number) => number): { biome: Uint8Array; temp: Float32Array; rain: Float32Array } {
  const biome = new Uint8Array(z.length), temp = new Float32Array(z.length), rain = new Float32Array(z.length);
  const wobble = new Noise2(4242);
  for (let j = 0; j < g.h; j++) {
    const lat = latOf(g.y0 + j * g.dy);
    // prevailing winds: trades from the east below 30°, westerlies 30-62°, polar easterlies above
    const fromWest = lat >= 30 && lat < 62;
    let moisture = 1;
    let prev = 0;
    for (let s = 0; s < g.w; s++) {
      const i = fromWest ? s : g.w - 1 - s;
      const k = j * g.w + i, h = z[k];
      const [cx0, cy0] = [g.x0 + i * g.dx, g.y0 + j * g.dy];
      const t = tempC(lat, h) + 0.8 * wobble.fbm(cx0 / 300, cy0 / 300, 3); // isotherms bend with the land
      temp[k] = t;
      if (h < 0 || lakes[k]) {
        moisture = Math.min(1, moisture + (h < 0 ? 0.08 : 0.02));
        rain[k] = moisture;
        biome[k] = h < 0 ? B('sea') : B('lake');
        prev = Math.max(0, h);
        continue;
      }
      const stepKm = g.dx * g.kmx(g.x0 + i * g.dx, g.y0 + j * g.dy);
      const rise = Math.max(0, h - prev);
      const lift = moisture * Math.min(0.6, rise / 1800);
      // rain falls where air climbs; the lee side stays drier, but never bone dry: land recycles some moisture
      moisture = Math.max(0.22, moisture - lift - 0.0006 * stepKm);
      prev = h;
      const r = Math.min(1, 0.35 * moisture + 3 * lift + 0.06);
      rain[k] = r;
    }
  }
  // the rain field, smoothed: weather does not follow grid rows
  const rad2 = Math.max(2, Math.round(40 / (g.dx * g.kmx(0, g.y0)))) | 0;
  const tmp = new Float32Array(rain.length), sm = new Float32Array(rain.length);
  for (let j = 0; j < g.h; j++) { let acc = 0, cnt = 0; for (let i = -rad2; i < g.w + rad2; i++) { if (i + rad2 < g.w) { acc += rain[j * g.w + i + rad2]; cnt++; } if (i - rad2 - 1 >= 0) { acc -= rain[j * g.w + i - rad2 - 1]; cnt--; } if (i >= 0 && i < g.w) tmp[j * g.w + i] = acc / cnt; } }
  for (let i = 0; i < g.w; i++) { let acc = 0, cnt = 0; for (let j = -rad2; j < g.h + rad2; j++) { if (j + rad2 < g.h) { acc += tmp[(j + rad2) * g.w + i]; cnt++; } if (j - rad2 - 1 >= 0) { acc -= tmp[(j - rad2 - 1) * g.w + i]; cnt--; } if (j >= 0 && j < g.h) sm[j * g.w + i] = acc / cnt; } }
  for (let k = 0; k < z.length; k++) {
    {
      const h = z[k];
      if (h < 0 || lakes[k]) continue;
      // rain is patchy: a large-scale wobble on the big frames, so wet and dry land interfinger rather than following the coast
      const t = temp[k], r = g.w >= 1536 ? sm[k] * (1 + 0.45 * wobble.fbm((k % g.w) / 40 + 7.3, Math.floor(k / g.w) / 40 + 3.1, 4)) : sm[k];
      rain[k] = r;
      let b: Biome;
      if (t < -12) b = 'ice';
      else if (h > 1700 && t < 1) b = 'alpine';
      else if (t < -2) b = 'tundra';
      else if (t < 4.5) b = r < 0.12 ? 'tundra' : 'boreal pine forest';
      else if (t < 14) b = r < 0.12 ? 'steppe' : r < 0.26 ? 'temperate grassland' : 'temperate forest';
      else if (t < 20) b = r < 0.09 ? 'desert' : r < 0.16 ? 'steppe' : r < 0.3 ? 'dry savanna' : 'subtropical forest';
      else b = r < 0.09 ? 'desert' : r < 0.25 ? 'dry savanna' : 'tropical forest';
      biome[k] = B(b);
    }
  }
  return { biome, temp, rain };
}

