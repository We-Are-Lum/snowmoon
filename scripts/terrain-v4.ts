// ---- projected frames: x = km east along the standard parallel, y = km north
type Frame = GridSpec & { lon0: number; lat0: number; phi: number; kx: number; lat: (y: number) => number; toLL: (x: number, y: number) => XY; fromLL: (lon: number, lat: number) => XY; render: number };
function projFrame(name: string, lon0: number, lat0: number, lon1: number, lat1: number, phi: number, w: number, render: number): Frame {
  const kx = 111.2 * Math.cos(rad(phi));
  const dx = ((lon1 - lon0) * kx) / w;
  const h = Math.round(((lat1 - lat0) * 111.2) / dx);
  const lat = (y: number) => lat0 + y / 111.2;
  return {
    name, w, h, x0: 0, y0: 0, dx, dy: dx, kmy: 1, edgeOutlet: true,
    kmx: (_x, y) => Math.cos(rad(lat(y))) / Math.cos(rad(phi)),
    lon0, lat0, phi, kx, lat, render,
    toLL: (x, y) => [lon0 + x / kx, lat(y)],
    fromLL: (lon, la) => [(lon - lon0) * kx, (la - lat0) * 111.2],
  };
}
