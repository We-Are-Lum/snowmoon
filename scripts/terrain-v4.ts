// ---- geometry helpers in a frame's own coordinates (corrected to true km)
const idx = (g: GridSpec, i: number, j: number) => j * g.w + i;
const cxy = (g: GridSpec, k: number): XY => [g.x0 + (k % g.w) * g.dx, g.y0 + Math.floor(k / g.w) * g.dy];
function kmDist(g: GridSpec, a: XY, b: XY): number {
  return Math.hypot((a[0] - b[0]) * g.kmx((a[0] + b[0]) / 2, (a[1] + b[1]) / 2), (a[1] - b[1]) * g.kmy);
}
function segKm(g: GridSpec, p: XY, a: XY, b: XY): number {
  const sx = g.kmx(p[0], p[1]);
  const ax = (a[0] - p[0]) * sx, ay = a[1] - p[1], bx = (b[0] - p[0]) * sx, by = b[1] - p[1];
  const dx = bx - ax, dy = by - ay, t = Math.max(0, Math.min(1, -(ax * dx + ay * dy) / (dx * dx + dy * dy || 1)));
  return Math.hypot(ax + t * dx, ay + t * dy);
}
/** Signed distance to a polygon (positive inside). Edges marked open (a drawing's own border, not a coast) are not counted. */
function polySigned(g: GridSpec, p: XY, poly: XY[], open?: boolean[]): number {
  let d = Infinity;
  for (let i = 0; i < poly.length; i++) if (!open?.[i]) d = Math.min(d, segKm(g, p, poly[i], poly[(i + 1) % poly.length]));
  return pointInPoly(p[0], p[1], poly) ? d : -d;
}
/** Clip a polygon to a convex polygon (Sutherland–Hodgman). */
function clipPoly(poly: XY[], clipper: XY[]): XY[] {
  let out = poly;
  for (let e = 0; e < clipper.length; e++) {
    const A = clipper[e], Bp = clipper[(e + 1) % clipper.length];
    const inside = (p: XY) => (Bp[0] - A[0]) * (p[1] - A[1]) - (Bp[1] - A[1]) * (p[0] - A[0]) >= 0;
    const cross = (p: XY, q: XY): XY => {
      const a1 = Bp[1] - A[1], b1 = A[0] - Bp[0], c1 = a1 * A[0] + b1 * A[1];
      const a2 = q[1] - p[1], b2 = p[0] - q[0], c2 = a2 * p[0] + b2 * p[1];
      const det = a1 * b2 - a2 * b1;
      return [(b2 * c1 - b1 * c2) / det, (a1 * c2 - a2 * c1) / det];
    };
    const inp = out;
    out = [];
    for (let i = 0; i < inp.length; i++) {
      const cur = inp[i], prev = inp[(i + inp.length - 1) % inp.length];
      if (inside(cur)) { if (!inside(prev)) out.push(cross(prev, cur)); out.push(cur); }
      else if (inside(prev)) out.push(cross(prev, cur));
    }
  }
  return out;
}
function lineKm(g: GridSpec, p: XY, line: XY[]): number {
  let d = Infinity;
  for (let i = 0; i < line.length - 1; i++) d = Math.min(d, segKm(g, p, line[i], line[i + 1]));
  return d;
}
function bilinear(g: GridSpec, z: Float32Array, x: number, y: number): number {
  const fi = (x - g.x0) / g.dx, fj = (y - g.y0) / g.dy;
  const i0 = Math.max(0, Math.min(g.w - 2, Math.floor(fi))), j0 = Math.max(0, Math.min(g.h - 2, Math.floor(fj)));
  const tx = Math.max(0, Math.min(1, fi - i0)), ty = Math.max(0, Math.min(1, fj - j0));
  const a = z[idx(g, i0, j0)], b = z[idx(g, i0 + 1, j0)], c = z[idx(g, i0, j0 + 1)], d = z[idx(g, i0 + 1, j0 + 1)];
  return (a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty;
}

